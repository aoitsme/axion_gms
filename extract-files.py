def post_regenerate_customizations():
    import re
    from pathlib import Path

    MY_DIR = Path(__file__).parent
    DEVICE_DIR = MY_DIR / 'common'
    COMMON_VENDOR_MK = DEVICE_DIR / 'common-vendor.mk'
    ANDROIDMK = DEVICE_DIR / 'Android.mk'
    ANDROIDBP = DEVICE_DIR / 'Android.bp'
    BOARDMK = DEVICE_DIR / 'BoardConfig.mk'

    if not COMMON_VENDOR_MK.exists():
        raise FileNotFoundError(f"{COMMON_VENDOR_MK} not generated; run extraction first?")

    if ANDROIDMK.exists():
        with open(ANDROIDMK, 'r') as f:
            content = f.read()
        content = re.sub(r'TARGET_DEVICE', 'TARGET_ARCH', content)
        with open(ANDROIDMK, 'w') as f:
            f.write(content)

    with open(COMMON_VENDOR_MK, 'r') as f:
        content = f.read()
    content = re.sub(r'vendor/gms/common{2,}/', 'vendor/gms/common/', content)
    content = re.sub(r'(vendor/gms/)(?!common)', r'\1common/', content)

    copy_lines = []
    copy_start = content.find('PRODUCT_COPY_FILES += ')
    if copy_start != -1:
        copy_end = content.find('PRODUCT_PACKAGES += ', copy_start)
        if copy_end == -1:
            copy_end = len(content)
        for line in content[copy_start:copy_end].splitlines()[1:]:
            l = line.strip()
            if l.endswith('\\'):
                l = l[:-1].strip()
            if l.startswith('vendor/gms/common/proprietary/'):
                copy_lines.append(l)

    pico_pkgs = list(PICO_PACKAGES)
    core_pkgs = pico_pkgs + list(CORE_EXTRA_PACKAGES)
    gms_pkgs = core_pkgs + list(GMS_EXTRA_PACKAGES)

    def fmt_list(prefix, items):
        if not items:
            return ''
        s = f'{prefix} += \\\n'
        for i, item in enumerate(items):
            sep = '' if i == len(items) - 1 else ' \\'
            s += f'    {item}{sep}\n'
        return s + '\n'

    out = '# Automatically generated file. DO NOT MODIFY\n#\n'
    out += '# Generated by vendor/gms/extract-files.py\n\n'
    out += 'PRODUCT_SOONG_NAMESPACES += \\\n    vendor/gms/common\n\n'
    out += fmt_list('PRODUCT_COPY_FILES', copy_lines)

    out += 'TARGET_GAPPS_VARIANT ?= gms\n'
    out += 'ifeq ($(strip $(TARGET_CORE_GMS)),true)\n'
    out += 'TARGET_GAPPS_VARIANT := core\n'
    out += 'endif\n\n'
    out += 'ifeq ($(strip $(TARGET_GAPPS_VARIANT)),pico)\n'
    out += fmt_list('PRODUCT_PACKAGES', pico_pkgs)
    out += 'else ifeq ($(strip $(TARGET_GAPPS_VARIANT)),core)\n'
    out += fmt_list('PRODUCT_PACKAGES', core_pkgs)
    out += 'else\n'
    out += fmt_list('PRODUCT_PACKAGES', gms_pkgs)
    out += 'endif\n'

    with open(COMMON_VENDOR_MK, 'w') as f:
        f.write(out)

    for mk_file in [ANDROIDBP, ANDROIDMK, BOARDMK, COMMON_VENDOR_MK]:
        if mk_file.exists():
            with open(mk_file, 'r') as f:
                c = f.read()
            c = re.sub(r'device/gms//setup-makefiles\.sh', 'vendor/gms/setup-makefiles.sh', c)
            with open(mk_file, 'w') as f:
                f.write(c)

    print(
        f"Custom makefile generations complete: "
        f"pico={len(pico_pkgs)} core={len(core_pkgs)} gms={len(gms_pkgs)}."
    )


